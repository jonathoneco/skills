#!/usr/bin/env bash
# Regenerate skills/<category>/README.md from each skill's frontmatter: one line per
# skill, split by whether a person or the model invokes it. Run after adding,
# removing, or redescribing a skill; commit the READMEs with the change.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

# description_of <SKILL.md>: the frontmatter description on one line, quotes and their escapes
# removed. A folded (`>`) or literal (`|`) description continues on the indented lines below it,
# joined with spaces.
description_of() {
  awk 'NR == 1 && /^---/ {f = 1; next} f && /^---/ {if (block) print text; exit}
       block && /^[[:space:]]/ {sub(/^[[:space:]]+/, ""); text = text (text ? " " : "") $0; next}
       block {print text; exit}
       f && /^description:/ {sub(/^description:[[:space:]]*/, "")
                             if ($0 ~ /^[>|][-+]?$/) {block = 1; next}
                             print; exit}' "$1" \
    | sed -e '/^".*"$/{s/^"\(.*\)"$/\1/;s/\\"/"/g;}' -e "/^'.*'\$/{s/^'\(.*\)'\$/\1/;s/''/'/g;}"
}

# write_category_readme <category>: one line per skill, split by who invokes it.
write_category_readme() {
  local category=$1 readme="skills/$1/README.md" skill_md name line user="" model=""
  for skill_md in "skills/$category"/*/SKILL.md; do
    name=$(basename "$(dirname "$skill_md")")
    line="- [$name](./$name/SKILL.md): $(description_of "$skill_md")"
    if grep -q '^disable-model-invocation: true' "$skill_md"; then
      user+="$line"$'\n'
    else
      model+="$line"$'\n'
    fi
  done
  {
    echo "# $category"
    echo
    echo "Generated by \`scripts/category-readmes.sh\` from each skill's frontmatter. Edit the skill, not this file."
    if [ -n "$user" ]; then
      printf '\n## User-invoked\n\n%s' "$user"
    fi
    if [ -n "$model" ]; then
      printf '\n## Model-invoked\n\n%s' "$model"
    fi
  } > "$readme"
}

for dir in skills/*/; do
  category=$(basename "$dir")
  ls "$dir"*/SKILL.md >/dev/null 2>&1 && write_category_readme "$category"
done
